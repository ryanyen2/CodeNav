"""Block Markdown ⇄ ``BlockSpec`` list. Pure: no store, no ids minted.

    # Title {#b-id}             heading; level = number of hashes; the id is optional
    A paragraph.                paragraph; one line (wrapped lines join with a space)
    - point                     bullet
    1. step                     numbered
        - nested                deeper indent = one level deeper
    | a | b |                   table: consecutive lines starting with `|`
    ```mermaid                  diagram (`mermaid derived` = redrawn from the code graph)
    ```python                   code; the info word is its `lang`
    ```codoc:image {#b-id}      any other kind: its content as one JSON object

This is the format of ``tree.codoc``, of a feature's description as a model
reads and writes it, and of one block's text in a block-keyed amend.

``parse(render(specs)) == specs`` (fuzzed in the tests) when each prose
``text`` is inline Markdown as ``inline_md.render`` writes it: that renderer
escapes a leading ``#``, ``- ``, ``1. `` or ``|``, so a paragraph never reads
as another block.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

from codoc.calculus.doc import (
    BULLET, CODE_BLOCK, DIAGRAM, HEADING, ITEMS, MAX_LEVEL, NUMBERED, PARAGRAPH, SOURCE, TABLE,
)

_HEADING = re.compile(r"^(#{1,6}) (.*?)(?: \{#(b-[0-9a-f]+)\})?$")
_ITEM = re.compile(r"^([ \t]*)(?:[-+*]|(\d{1,9})\.) +(.*)$")
_FENCE = re.compile(r"^(`{3,})\s*([^\s`{]*)([^`{]*?)(?:\{#(b-[0-9a-f]+)\})?\s*$")
INDENT = "    "      # per list level; four columns nests under both `- ` and `1. ` on GitHub
# The export's first line (``render(..., generated=True)``). The file is derived
# from the log and rewritten on every publish, so a hand edit to it is lost;
# ``parse`` skips this line.
GENERATED = "<!-- Generated by codoc from .codoc/log. Edits to this file are overwritten; edit the tree in the codoc editor. -->"


@dataclass(frozen=True)
class BlockSpec:
    """One block as Markdown says it.

    ``text`` is inline Markdown for a prose kind and the raw source for a
    source kind (table, diagram, code). ``content`` holds the non-Text fields;
    for a kind written as a JSON fence it also holds the Text fields, as
    Markdown strings, and for a plugin kind ``$layout``, which names them.
    ``id`` is set only where the Markdown carried one."""
    kind: str
    level: int = 0
    text: str = ""
    content: dict = field(default_factory=dict)
    id: str | None = None


# ── parse ────────────────────────────────────────────────────────────────────

def parse(md: str, *, headings: bool = True, absolute: bool = False) -> list[BlockSpec]:
    """The blocks ``md`` describes, in order. With ``headings=False`` a
    ``# line`` is a paragraph without its hashes: a description cannot hold a
    heading, because a heading is a feature.

    An item's level is relative: one deeper than the open item it is indented
    past. With ``absolute`` it is read from its own indent instead: level 1
    flush left, one more per started four columns. That is how ``render_one``
    shows a block alone, so a level written back from it is absolute."""
    out: list[BlockSpec] = []
    lines = md.replace("\r\n", "\n").split("\n")
    if lines[0].strip() == GENERATED:
        lines = lines[1:]
    para: list[str] = []
    indents: list[int] = []        # indent width of each open list level
    i = 0

    def flush() -> None:
        if para:
            text = para[0].strip() if len(para) == 1 else " ".join(l.strip() for l in para)
            para.clear()
            if text:
                out.append(BlockSpec(PARAGRAPH, text=text))

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            flush()
            i += 1
            continue
        if fence := _FENCE.match(stripped):
            flush()
            indents.clear()
            body, i = _fence_body(lines, i + 1, len(fence.group(1)))
            out.append(_fenced(fence.group(2), fence.group(3).split(), fence.group(4), body))
            continue
        if stripped.startswith("|"):
            flush()
            indents.clear()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i].strip())
                i += 1
            out.append(BlockSpec(TABLE, text="\n".join(rows)))
            continue
        if item := _ITEM.match(line):
            flush()
            width = len(item.group(1).expandtabs(4))
            while indents and width < indents[-1]:
                indents.pop()
            if not indents or width > indents[-1]:
                indents.append(width)
            text = item.group(3).strip()
            i += 1
            # A wrapped item: indented lines that are not items themselves.
            while i < len(lines) and lines[i][:1] in (" ", "\t") and lines[i].strip() \
                    and not _ITEM.match(lines[i]) and not lines[i].strip().startswith(("|", "```")):
                text += " " + lines[i].strip()
                i += 1
            level = 1 + -(-width // 4) if absolute else len(indents)
            out.append(BlockSpec(NUMBERED if item.group(2) else BULLET, min(level, MAX_LEVEL), text))
            continue
        if h := _HEADING.match(stripped):
            flush()
            indents.clear()
            if headings:
                out.append(BlockSpec(HEADING, len(h.group(1)), h.group(2).strip(), id=h.group(3)))
            elif h.group(2).strip():
                out.append(BlockSpec(PARAGRAPH, text=h.group(2).strip()))
            i += 1
            continue
        indents.clear()
        para.append(line)
        i += 1
    flush()
    return out


def _fence_body(lines: list[str], i: int, ticks: int) -> tuple[str, int]:
    """Lines up to the closing fence (at least ``ticks`` backticks and nothing
    else), and the index after it. An unclosed fence runs to the end."""
    body: list[str] = []
    while i < len(lines):
        s = lines[i].strip()
        if len(s) >= ticks and set(s) == {"`"}:
            return "\n".join(body), i + 1
        body.append(lines[i])
        i += 1
    return "\n".join(body), i


def _fenced(info: str, words: list[str], bid: str | None, body: str) -> BlockSpec:
    if info == "mermaid":
        return BlockSpec(DIAGRAM, text=body, content={"derived": True} if "derived" in words else {})
    if info.startswith("codoc:"):
        try:
            content = json.loads(body or "{}")
        except json.JSONDecodeError:
            content = None
        if isinstance(content, dict):
            kind = info[len("codoc:"):]
            source = content.pop("source", "") if kind in SOURCE else ""
            return BlockSpec(kind, text=source if isinstance(source, str) else "", content=content, id=bid)
    return BlockSpec(CODE_BLOCK, text=body, content={"lang": info} if info else {})


# ── render ───────────────────────────────────────────────────────────────────

def render(specs: list[BlockSpec], *, ids: bool = False, generated: bool = False) -> str:
    """Markdown for ``specs``: one blank line between blocks, none between
    consecutive list items. ``ids`` writes each heading's id; ``generated``
    starts with the ``GENERATED`` line, as the export does.

    Markdown nests a list one level at a time, so an item more than one level
    deeper than the block before it is written one level deeper."""
    out: list[str] = [GENERATED] if generated else []
    counters: dict[int, int] = {}       # numbered-list position per level
    prev_level = 0                      # level of the previous block when it was an item
    top_kind = None                     # kind of the last level-1 item in this run of items
    for s in specs:
        if s.kind not in ITEMS:
            if out:
                out.append("")
            counters.clear()
            prev_level, top_kind = 0, None
            out.extend(_block(s, ids))
            continue
        level = min(max(1, s.level), prev_level + 1)
        # A blank line starts a list, and separates a bullet list from a numbered one.
        if out and (not prev_level or (level == 1 and s.kind != top_kind)):
            out.append("")
        if level == 1:
            top_kind = s.kind
        for deeper in [l for l in counters if l > level]:
            del counters[deeper]
        if s.kind == NUMBERED:
            counters[level] = counters.get(level, 0) + 1
            marker = f"{counters[level]}."
        else:
            counters.pop(level, None)
            marker = "-"
        out.append(f"{INDENT * (level - 1)}{marker} {s.text}")
        prev_level = level
    return "\n".join(out) + "\n" if out else ""


def render_one(s: BlockSpec) -> str:
    """One block on its own, as a block-keyed prompt shows it: a list item
    keeps its own indent and a numbered one reads ``1.``. ``parse`` of the
    result gives the same kind and text; an item's level is not recoverable
    from one block, so a caller that rewrites an existing block keeps the
    level it has."""
    if s.kind in ITEMS:
        return f"{INDENT * (max(1, s.level) - 1)}{'1.' if s.kind == NUMBERED else '-'} {s.text}"
    return "\n".join(_block(s, ids=False))


def _block(s: BlockSpec, ids: bool) -> list[str]:
    if s.kind == HEADING:
        tail = f" {{#{s.id}}}" if ids and s.id else ""
        return [f"{'#' * max(1, s.level)} {s.text}{tail}"]
    if s.kind == PARAGRAPH:
        return [s.text]
    return _native(s) or _json_fence(s)


def _native(s: BlockSpec) -> list[str] | None:
    """A source block in its own Markdown form, or None when that form cannot
    say it (extra fields, a table line that is not a row, an info word the
    parser would read as something else)."""
    c = s.content
    if s.kind == TABLE:
        lines = s.text.split("\n")
        ok = not c and bool(s.text) and all(l.startswith("|") and l == l.strip() for l in lines)
        return lines if ok else None
    if s.kind == DIAGRAM and (not c or c == {"derived": True}):
        return _fence("mermaid derived" if c else "mermaid", s.text)
    if s.kind == CODE_BLOCK and (not c or (set(c) == {"lang"} and _is_lang(c["lang"]))):
        return _fence(c.get("lang", ""), s.text)
    return None


def _is_lang(v) -> bool:
    return isinstance(v, str) and bool(re.fullmatch(r"[^\s`{]+", v)) and v != "mermaid" and not v.startswith("codoc:")


def _json_fence(s: BlockSpec) -> list[str]:
    content = dict(s.content)
    if s.kind in SOURCE:
        content["source"] = s.text
    tail = f" {{#{s.id}}}" if s.id else ""
    return [f"```codoc:{s.kind}{tail}", json.dumps(content, ensure_ascii=False, sort_keys=True), "```"]


def _fence(info: str, source: str) -> list[str]:
    """A fence one backtick longer than any all-backtick line in ``source``."""
    runs = [len(l.strip()) for l in source.split("\n") if len(l.strip()) >= 3 and set(l.strip()) == {"`"}]
    ticks = "`" * (max(runs) + 1 if runs else 3)
    return [f"{ticks}{info}", *source.split("\n"), ticks]
