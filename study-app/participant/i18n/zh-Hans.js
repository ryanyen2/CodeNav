//   subscales collapse together in HCI work.
//
//   Names of things stay in the language the participant will SEE them in. The
//   code, the file names, the commands and the two projects are all in English on
//   their screen, so `CLAUDE.md`, `scribe`, `tally` and every path stay verbatim.
